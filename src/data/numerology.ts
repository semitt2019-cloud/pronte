// ---------------- วิเคราะห์เบอร์ ----------------
// อ่าน 7 ตัวท้ายเป็นคู่ซ้อนกัน 6 คู่ ให้น้ำหนักคู่ท้ายมากกว่า (คนจำและพูดถึงตัวท้ายบ่อยที่สุด)
const WEIGHTS = [1, 1, 1, 1.5, 2, 3];
const SUM_W = 1.5;
const val = (t: Tone) => (t === 'ดี' ? 1 : t === 'เสีย' ? -1 : 0);

export type Grade = { grade: string; label: string; cls: 'a' | 'b' | 'c' | 'd' };
export const gradeOf = (score: number): Grade =>
  score >= 80 ? { grade: 'A+', label: 'ดีเยี่ยม', cls: 'a' }
  : score >= 70 ? { grade: 'A', label: 'ดีมาก', cls: 'a' }
  : score >= 62 ? { grade: 'B+', label: 'ดี', cls: 'b' }
  : score >= 55 ? { grade: 'B', label: 'ค่อนข้างดี', cls: 'b' }
  : score >= 45 ? { grade: 'C', label: 'กลาง ๆ', cls: 'c' }
  : { grade: 'D', label: 'ควรพิจารณา', cls: 'd' };

export type Analysis = {
  digits: string; sum: number; sumInfo: Meaning;
  pairs: { pair: string; pos: number; weight: number; tone: Tone; text: string; topic?: string }[];
  good: number; bad: number; score: number; topics: string[];
} & Grade;

export function analyze(raw: string): Analysis | null {
  const digits = raw.replace(/\D/g, '');
  if (digits.length !== 10) return null;
  const tail = digits.slice(3);
  const pairs = WEIGHTS.map((w, i) => {
    const pair = tail.slice(i, i + 2);
    return { pair, pos: i, weight: w, ...PAIRS[pair] };
  });
  const sum = digits.split('').reduce((a, d) => a + +d, 0);
  const sumInfo = sumMeaning(sum);
  const raw_ = pairs.reduce((a, p) => a + val(p.tone) * p.weight, 0) + val(sumInfo.tone) * SUM_W;
  const max = WEIGHTS.reduce((a, b) => a + b, 0) + SUM_W;
  const score = Math.round(50 + 50 * (raw_ / max));
  const topics = [...new Set(pairs.filter((p) => p.tone === 'ดี' && p.topic).sort((a, b) => b.weight - a.weight).map((p) => p.topic!))];
  return {
    digits, sum, sumInfo, pairs, score, topics,
    good: pairs.filter((p) => p.tone === 'ดี').length,
    bad: pairs.filter((p) => p.tone === 'เสีย').length,
    ...gradeOf(score),
  };
}
